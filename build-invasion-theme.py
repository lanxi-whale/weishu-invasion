"""Generate camp-scoped dark crimson CSS and UI-only sprite variants (never battle/portrait art)."""
import colorsys
import hashlib
import io
import json
import re
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent
COLOR = re.compile(r'#[0-9a-fA-F]{3,8}\b|rgba?\(\s*[\d.]+\s*,\s*[\d.]+\s*,\s*[\d.]+(?:\s*,\s*[\d.]+)?\s*\)')


def recolor(match):
    raw = match.group()
    if raw.startswith('#'):
        h = raw[1:]
        if len(h) in (3, 4):
            h = ''.join(c * 2 for c in h)
        if len(h) not in (6, 8):
            return raw
        rgb = [int(h[i:i + 2], 16) for i in (0, 2, 4)]
        alpha = h[6:]
    else:
        parts = re.findall(r'[\d.]+', raw)
        rgb = list(map(float, parts[:3]))
        alpha = parts[3] if len(parts) == 4 else None
    hue, sat, val = colorsys.rgb_to_hsv(*(x / 255 for x in rgb))
    if not (0.22 <= hue <= 0.55 and sat >= .08):
        return raw
    # Dark surfaces remain almost black; bright mint becomes legible muted rose.
    converted = colorsys.hsv_to_rgb(.985, min(sat, .62), val * .85)
    r, g, b = (round(x * 255) for x in converted)
    if raw.startswith('#'):
        return f'#{r:02x}{g:02x}{b:02x}' + alpha
    return f'rgba({r}, {g}, {b}, {alpha})' if alpha is not None else f'rgb({r}, {g}, {b})'


def rules(source):
    """Walk balanced CSS blocks, retaining only changed colour declarations and media wrappers."""
    source = re.sub(r'/\*.*?\*/', '', source, flags=re.S)
    output = []
    pos = 0
    while pos < len(source):
        opening = source.find('{', pos)
        if opening < 0:
            break
        header = source[pos:opening].strip()
        depth, end, quote = 1, opening + 1, None
        while end < len(source) and depth:
            c = source[end]
            if quote:
                if c == quote and source[end - 1] != '\\':
                    quote = None
            elif c in ('"', "'"):
                quote = c
            elif c == '{':
                depth += 1
            elif c == '}':
                depth -= 1
            end += 1
        body = source[opening + 1:end - 1]
        pos = end
        if header.startswith(('@media', '@supports', '@layer')):
            child = rules(body)
            if child:
                output.append(header + '{\n' + child + '}')
        elif not header.startswith('@') and '.camp' not in header:
            declarations = []
            for declaration in body.split(';'):
                if ':' not in declaration:
                    continue
                prop, value = declaration.split(':', 1)
                if prop.strip().startswith(('--tier-', '--lv-', '--diff-')):
                    continue
                new = COLOR.sub(recolor, value)
                if new != value:
                    declarations.append(prop.strip() + ':' + new.strip())
            if declarations:
                output.append(header + '{' + ';'.join(declarations) + ';}')
    return '\n'.join(output) + ('\n' if output else '')


def main():
    public = ROOT / 'game/public'
    styles = re.findall(r'href="(/css/[^"?]+\.css)"', (public / 'index.html').read_text('utf-8'))
    css = '/* Generated by build-invasion-theme.py. Keep semantic rarity/difficulty colours. */\n'
    # The shared lobby, Alliance roster and watched Alliance bonds use their own palettes.
    css += '@scope (html[data-camp="monster"]) to (.lobby-hub, .rs-camp--ops, .gm__bonds[data-bond-camp="ops"]) {\n'
    for path in styles:
        if path.endswith('/invasion-theme.css'):
            continue
        css += rules((public / path.lstrip('/')).read_text('utf-8'))
    css += '}\n'
    css += (ROOT / 'invasion-controls.css').read_text('utf-8')
    manifest = json.loads((ROOT / 'game/data/local-assets.json').read_text('utf-8'))
    variants = {}
    # Exact UI chrome only: art-bearing season/entry/camp groups are intentionally excluded.
    for group in ('ui/battle', 'ui/common', 'ui/outer'):
        for name, entry in manifest['groups'].get(group, {}).items():
            if not name.startswith(('img_', 'btn_')) or any(x in name for x in ('portrait', 'avatar', 'char_', 'head_', 'enemy')):
                continue
            path = entry.get('path', '')
            src = public / path.lstrip('/')
            if not src.is_file() or src.suffix.lower() not in ('.png', '.webp'):
                continue
            image = Image.open(src).convert('RGBA')
            pixels = np.array(image)
            rgb = pixels[:, :, :3].astype(float)
            r, g, b = (rgb[:, :, i] for i in range(3))
            mask = (g > r * 1.12) & (g > b * .85) & (g > 20) & (pixels[:, :, 3] > 0)
            if not mask.any():
                continue
            rgb[mask] = np.stack((g * .85, r * .48 + g * .24, b * .28 + r * .35), axis=-1)[mask]
            pixels[:, :, :3] = np.clip(rgb, 0, 255).astype('uint8')
            out = io.BytesIO()
            Image.fromarray(pixels).save(out, 'WEBP', lossless=True)
            encoded = out.getvalue()
            digest = hashlib.sha256(encoded).hexdigest()[:12]
            dest = '/assets/local/ui/invasion/' + digest + '.webp'
            variants[group + '/' + name] = dict(entry, path=dest)
            for camp in ('game', 'game_ops'):
                target = ROOT / camp / 'public' / dest.lstrip('/')
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(encoded)
    for camp in ('game', 'game_ops'):
        (ROOT / camp / 'public/css/invasion-theme.css').write_text(css, 'utf-8')
        path = ROOT / camp / 'data/local-assets.json'
        doc = json.loads(path.read_text('utf-8'))
        doc['groups']['ui/invasion'] = variants
        doc['count'] = sum(len(group) for group in doc['groups'].values())
        path.write_text(json.dumps(doc, ensure_ascii=False, separators=(',', ':')), 'utf-8')
    print('Generated', len(css), 'CSS bytes and', len(variants), 'UI sprite variants')


if __name__ == '__main__':
    main()
