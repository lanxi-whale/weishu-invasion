def surface_grade(image):
    pixels = np.asarray(image).astype(np.float32)
    vertical, horizontal = np.ogrid[:SIZE[1], :SIZE[0]]
    horizontal = horizontal / SCALE
    vertical = vertical / SCALE
    rng = np.random.default_rng(3401)
    grain = rng.normal(0, 1.45, pixels.shape[:2])
    variation = Image.fromarray(rng.integers(0, 256, size=(84, 82), dtype=np.uint8))
    variation = np.asarray(variation.resize(SIZE,Image.Resampling.BICUBIC),dtype=np.float32)/255-.5
    contrast = .84 + .25 * np.exp(-((horizontal-398)/298)**2 - ((vertical-356)/280)**2)
    lamplight = np.exp(-((horizontal-453)/117)**2-((vertical-204)/115)**2)
    pixels[:, :, :3] *= (contrast+variation*.14)[..., None]
    pixels[:, :, :3] += (variation*3+grain)[..., None] + lamplight[..., None]*[9,1,0]
    edge = np.clip(np.minimum(horizontal, WIDTH-horizontal) / 21, 0, 1)
    base = 1 - np.clip((vertical-719)/42, 0, 1)**1.25
    pixels[:, :, 3] *= edge * base * np.clip(vertical/13, 0, 1)
    return Image.fromarray(pixels.clip(0, 255).astype(np.uint8))


def build():
    art = Canvas()
    distant_structures(art)
    facade(art)
    crown(art)
    masonry(art)
    foreground(art)
    paint_damage(art)
    lamps, keys = light_paint()
    bloom = Image.new('RGBA', SIZE, '#ad3e37')
    bloom.putalpha(lamps.getchannel('A').filter(ImageFilter.GaussianBlur(6 * SCALE)))
    painting = Image.alpha_composite(art.image, bloom)
    painting = Image.alpha_composite(painting, keys)
    painting = Image.alpha_composite(painting, lamps)
    return surface_grade(painting)


