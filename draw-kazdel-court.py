def coords(points):
    return [(round(horizontal * SCALE), round(vertical * SCALE)) for horizontal, vertical in points]


class Canvas:
    def __init__(self):
        self.image = Image.new('RGBA', SIZE)
        self.draw = ImageDraw.Draw(self.image)

    def fill(self, color, points):
        self.draw.polygon(coords(points), fill=color)

    def line(self, color, width, points):
        self.draw.line(coords(points), fill=color, width=max(1, round(SCALE * width)), joint='curve')

    def plate(self, points, face=IRON, rim=RIM, width=1.0):
        self.fill(face, points)
        self.line(rim, width, points[:3])

    def rivets(self, points, color='#80494d'):
        for horizontal, vertical in points:
            self.fill(color, [(horizontal, vertical), (horizontal + 1.8, vertical - .4),
                              (horizontal + 2.2, vertical + 1.2), (horizontal + .4, vertical + 1.7)])


